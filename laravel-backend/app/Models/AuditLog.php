<?php

namespace App\Models;

use MongoDB\Laravel\Eloquent\Model;

class AuditLog extends Model
{
    protected $connection = 'mongodb';
    protected $collection = 'audit_logs';

    protected $fillable = [
        'user_id',
        'user_name',
        'user_role',
        'action', // 'CREATE', 'UPDATE', 'APPROVE', 'VERIFY', 'ISSUE', 'COMPLETE_TRIP', 'ODOMETER_ADJUSTMENT'
        'module',
        'record_id',
        'old_values',
        'new_values',
        'reason',
        'ip_address',
    ];

    protected $casts = [
        'old_values' => 'array',
        'new_values' => 'array',
    ];

    public function user()
    {
        return $this->belongsTo(User::class, 'user_id');
    }
}
